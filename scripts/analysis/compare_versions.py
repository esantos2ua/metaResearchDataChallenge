"""Compare corpus versions side by side: size, composition, and the landscape they draw.

Each version is a records.json written by build_records.py. The pilot comes from git history;
later pulls come from `build_records.py --out`:

    git show a6f50c2:dashboard/app/data/records.json > data/raw/records_pilot_2026-06-19.json
    python3 scripts/extraction/build_records.py --out data/raw/records_2026-10-14.json
    python3 scripts/analysis/compare_versions.py

Writes data/versions/comparison.md and data/versions/comparison.json.
"""

from __future__ import annotations

import json
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "data" / "versions"
VERSIONS = [
    ("pilot", "Pilot (proposal)", "OpenAlex API, 2026-06-19", ROOT / "data/raw/records_pilot_2026-06-19.json"),
    ("v1", "v1 frozen (after team + community)", "OpenAlex API, 2026-09-15", ROOT / "dashboard/app/data/records.json"),
    ("oct", "v1 config, October OpenAlex", "OpenAlex API, 2026-10-15 (snapshot of 2026-10-14)", ROOT / "data/raw/records_2026-10-14.json"),
]
TOP_N = 5


def canadian_institutions(rec: dict) -> set[str]:
    return {i["name"] for i in rec["institutions"] if i.get("country") == "CA"}


def profile(records: list[dict], meta: dict) -> dict:
    n = len(records)
    share = lambda k: round(k / n, 4)  # noqa: E731
    inst = Counter(name for r in records for name in canadian_institutions(r))
    top = inst.most_common(TOP_N)
    top_names = {name for name, _ in top}
    return {
        "works": n,
        "topics_in_definition": len(meta.get("topics") or {}),
        "works_per_topic": dict(Counter(t for r in records for t in r.get("topics", []))),
        "since_2015": share(sum(r["year"] >= 2015 for r in records)),
        "open_access": share(sum(bool(r["is_oa"]) for r in records)),
        "diamond": share(sum(r["oa_status"] == "diamond" for r in records)),
        "french": share(sum(r["language"] == "fr" for r in records)),
        "editorials": share(sum(r["type"] == "editorial" for r in records)),
        "international_coauthor": share(sum(any(i.get("country") not in (None, "CA") for i in r["institutions"])
                                            for r in records)),
        "canadian_lead_author": sum(bool(r.get("first_ca") or r.get("corr_ca")) for r in records),
        "canadian_institutions": len(inst),
        "top_institutions": top,
        "top_institutions_share": share(sum(bool(canadian_institutions(r) & top_names) for r in records)),
    }


def pct(x: float) -> str:
    return f"{100 * x:.1f}%"


def main() -> None:
    data, ids, names = {}, {}, {}
    for key, label, source, path in VERSIONS:
        payload = json.loads(path.read_text(encoding="utf-8"))
        data[key] = {"label": label, "source": source, "file": str(path.relative_to(ROOT)),
                     **profile(payload["records"], payload["meta"])}
        ids[key] = {r["id"] for r in payload["records"]}
        names.update(payload["meta"].get("topics") or {})

    flows = {}
    for a, b in (("pilot", "v1"), ("v1", "oct")):
        flows[f"{a}->{b}"] = {"kept": len(ids[a] & ids[b]), "left": len(ids[a] - ids[b]),
                              "entered": len(ids[b] - ids[a])}
    result = {"versions": data, "flows": flows}
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "comparison.json").write_text(json.dumps(result, indent=2, ensure_ascii=False), encoding="utf-8")

    keys = [k for k, *_ in VERSIONS]
    row = lambda name, f: f"| {name} | " + " | ".join(f(data[k]) for k in keys) + " |"  # noqa: E731
    lines = [
        "# Corpus versions compared",
        "",
        "Generated by `scripts/analysis/compare_versions.py`. Same Canadian filter in every version;",
        "the pilot used five topics, v1 and the October pull use the six in `query_config.yaml`.",
        "",
        "| | " + " | ".join(data[k]["label"] for k in keys) + " |",
        "| --- |" + " --- |" * len(keys),
        row("Source", lambda d: d["source"]),
        row("Topics in definition", lambda d: str(d["topics_in_definition"])),
        row("Works", lambda d: f"{d['works']:,}"),
        row("Canadian lead author", lambda d: f"{d['canadian_lead_author']:,}"),
        row("Published 2015 or later", lambda d: pct(d["since_2015"])),
        row("Open access", lambda d: pct(d["open_access"])),
        row("Diamond OA", lambda d: pct(d["diamond"])),
        row("French-language", lambda d: pct(d["french"])),
        row("Editorials", lambda d: pct(d["editorials"])),
        row("International co-author", lambda d: pct(d["international_coauthor"])),
        row("Canadian institutions", lambda d: f"{d['canadian_institutions']:,}"),
        row(f"Works with a top-{TOP_N} institution", lambda d: pct(d["top_institutions_share"])),
        row(f"Top {TOP_N} institutions", lambda d: "<br>".join(f"{n} ({c:,})" for n, c in d["top_institutions"])),
        "",
        "## Works per corpus topic (a work counts in each topic it carries)",
        "",
        "| Topic | " + " | ".join(data[k]["label"] for k in keys) + " |",
        "| --- |" + " --- |" * len(keys),
    ]
    topics = sorted({t for k in keys for t in data[k]["works_per_topic"]})
    for t in topics:
        lines.append(f"| {t} {names.get(t, '')} | " + " | ".join(f"{data[k]['works_per_topic'].get(t, 0):,}" for k in keys) + " |")
    lines += ["", "## Flows between versions", "", "| | Kept | Left | Entered |", "| --- | --- | --- | --- |"]
    for name, f in flows.items():
        lines.append(f"| {name} | {f['kept']:,} | {f['left']:,} | {f['entered']:,} |")
    (OUT / "comparison.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
